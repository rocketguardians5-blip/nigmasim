import type { ReactNode } from 'react'

interface AppIconProps {
  name: string
  className?: string
}

const PATHS: Record<string, ReactNode> = {
  users: (
    <>
      <circle cx="9" cy="8" r="3" />
      <path d="M3.5 19a5.5 5.5 0 0 1 11 0" strokeLinecap="round" />
      <path d="M16 5.5a3 3 0 0 1 0 5.8M17.5 19a5.5 5.5 0 0 0-2-4.2" strokeLinecap="round" />
    </>
  ),
  grid: (
    <>
      <rect x="4" y="4" width="7" height="7" rx="1.5" />
      <rect x="13" y="4" width="7" height="7" rx="1.5" />
      <rect x="4" y="13" width="7" height="7" rx="1.5" />
      <rect x="13" y="13" width="7" height="7" rx="1.5" />
    </>
  ),
}

/** Ikon inline (tanpa CDN/font eksternal). */
export function AppIcon({ name, className = 'h-5 w-5' }: AppIconProps) {
  const path = PATHS[name] ?? PATHS.grid
  return (
    <svg
      viewBox="0 0 24 24"
      className={className}
      fill="none"
      stroke="currentColor"
      strokeWidth="1.7"
      aria-hidden="true"
    >
      {path}
    </svg>
  )
}
